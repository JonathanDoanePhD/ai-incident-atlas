"""Write reports/data_profile.md: counts, coverage, missingness, duplicates, long tails."""

from __future__ import annotations

import pandas as pd

from atlas import paths
from atlas.ingest.load import connect


def _md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False)


def build() -> str:
    con = connect()
    q = lambda s: pd.read_sql_query(s, con)  # noqa: E731
    inc = q("SELECT * FROM incidents")
    rep = q("SELECT report_number, source_domain, date_published, language, text_chars, is_incident_report FROM reports")
    ir = q("SELECT * FROM incident_report")
    ie = q("SELECT * FROM incident_entity")
    el = q("SELECT * FROM expert_label")
    n = len(inc)
    out: list[str] = ["# Data profile — AIID snapshot 2026-11-02", "",
                      "_Generated by `python -m atlas.ingest.profile`. All numbers are computed from `data/atlas.sqlite`._", ""]

    out += ["## Record counts", ""]
    counts = q("SELECT table_name, row_count, source_file FROM provenance ORDER BY table_name")
    out += [_md(counts), ""]

    out += ["## Incidents", "",
            f"- Incidents: **{n}** (IDs {inc.incident_id.min()}–{inc.incident_id.max()})",
            f"- Incident date range: {inc.date.min()} → {inc.date.max()}",
            f"- Incidents flagged as duplicates of another incident (AIID `duplicates`): {inc.is_duplicate_of.notna().sum()}",
            f"- Duplicate titles (exact, case-insensitive): {inc.title.str.lower().duplicated().sum()}", ""]
    by_year = inc.groupby("year").size().rename("incidents").reset_index()
    out += ["### Incidents by year (incident date)", "", _md(by_year), ""]

    miss = pd.DataFrame({"column": inc.columns, "missing": [inc[c].isna().sum() for c in inc.columns]})
    miss["share"] = (miss.missing / n).round(3)
    out += ["### Missing values (incidents)", "", _md(miss), ""]

    rpi = ir.groupby("incident_id").size()
    rpi = rpi.reindex(inc.incident_id, fill_value=0)
    desc = rpi.describe(percentiles=[.25, .5, .75, .9, .99]).round(2).rename("reports per incident").reset_index()
    n_var = int((rep.is_incident_report == 0).sum())
    rep = rep[rep.is_incident_report == 1]
    out += ["## Reports", "",
            f"- Report records: **{len(rep) + n_var}**, of which {n_var} are AIID *variant* records "
            "(`is_incident_report = False`, mostly without a URL); they are excluded from the statistics below.",
            f"- News/incident reports: **{len(rep)}**; linked to ≥1 incident: {rep.report_number.isin(ir.report_number).sum()}",
            f"- Reports with no text: {(rep.text_chars == 0).sum()}; median text length {int(rep.text_chars.median())} chars",
            f"- Incidents with zero linked reports: {(rpi == 0).sum()}; with exactly one: {(rpi == 1).sum()}",
            f"- Reports linked to more than one incident: {(ir.groupby('report_number').size() > 1).sum()}", "",
            "### Reports per incident", "", _md(desc), ""]
    lang = rep.language.fillna("(missing)").value_counts().head(10).rename_axis("language").reset_index(name="reports")
    out += ["### Report languages (top 10)", "", _md(lang), ""]
    dom = rep.source_domain.fillna("(missing)").value_counts().head(15).rename_axis("source_domain").reset_index(name="reports")
    out += ["### Most frequent source domains", "", _md(dom), ""]

    out += ["## Entities", ""]
    role_counts = ie.groupby("role").agg(links=("entity_id", "size"), distinct_entities=("entity_id", "nunique")).reset_index()
    out += [_md(role_counts), ""]
    for role in ("developer", "deployer"):
        top = ie[ie.role == role].entity_id.value_counts()
        out += [f"### Top {role}s (incidents)", "", _md(top.head(15).rename_axis("entity_id").reset_index(name="incidents")), "",
                f"Long tail: {(top == 1).sum()} of {len(top)} {role} entities ({(top == 1).mean():.0%}) appear in exactly one incident.", ""]
    out += ["Harmed-party entity names are not listed here because some name private individuals (see `docs/ethics.md`).", ""]

    out += ["## Expert taxonomy coverage", "",
            "Share of the incidents carrying at least one label from each expert namespace (published or not).", ""]
    cov = el.groupby("namespace").incident_id.nunique().rename("incidents").reset_index()
    cov["share_of_incidents"] = (cov.incidents / n).round(3)
    out += [_md(cov), ""]
    any_cset_gmf = el[el.namespace.isin(["CSETv1", "GMF"])].incident_id.nunique()
    out += [f"- Incidents with CSETv1 **or** GMF labels: {any_cset_gmf} ({any_cset_gmf / n:.1%})",
            f"- Incidents with any expert label: {el.incident_id.nunique()} ({el.incident_id.nunique() / n:.1%})", ""]
    mit_year = inc.merge(el[el.namespace == "MIT"][["incident_id"]].drop_duplicates().assign(mit=1), how="left").fillna({"mit": 0})
    cov_y = mit_year.groupby("year").mit.mean().round(2).rename("MIT label coverage").reset_index()
    out += ["### MIT label coverage by incident year", "", _md(cov_y[cov_y.year >= 2010]), ""]

    text = "\n".join(out)
    paths.REPORTS.mkdir(exist_ok=True)
    (paths.REPORTS / "data_profile.md").write_text(text)
    return text


if __name__ == "__main__":
    print(build()[:3000])
